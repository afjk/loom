import { fileURLToPath, pathToFileURL } from 'node:url';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { LIBRARY_METADATA } from '../src/toolchain/library-metadata.js';

export function renderStandardLibraryReferenceMarkdown(metadata) {
  let content = `# Standard Library Reference

This file is generated from \`src/toolchain/library-metadata.js\`.
Do not edit this file manually. Update metadata and regenerate instead.

`;

  const libraries = Object.values(metadata);

  for (const library of libraries) {
    const status = library.status ?? 'implemented';
    const targets = (library.targets ?? []).join(', ') || 'none';

    content += `## ${library.name}\n\n`;
    content += `${library.description}\n\n`;
    content += `Targets: ${targets}\n`;
    content += `Status: ${status}\n\n`;

    const functions = Object.values(library.functions ?? {});

    if (functions.length === 0) {
      content += 'No functions documented.\n\n';
      continue;
    }

    for (const fn of functions) {
      content += `### ${library.name}.${fn.name}\n\n`;
      content += `Signature: \`${fn.signature}\`\n\n`;
      content += `Returns: \`${fn.returns ?? 'any'}\`\n`;

      const fnStatus = fn.status ?? 'implemented';
      content += `Status: \`${fnStatus}\`\n\n`;

      content += `${fn.description}\n\n`;

      const args = fn.args ?? [];
      if (args.length === 0) {
        content += 'Arguments: none\n\n';
      } else {
        content += 'Arguments:\n\n';
        content += '| Name | Type | Positional | Description |\n';
        content += '|---|---|---:|---|\n';
        for (const arg of args) {
          const positional = arg.positional ? 'yes' : 'no';
          content += `| ${arg.name} | ${arg.type ?? 'any'} | ${positional} | ${arg.description ?? ''} |\n`;
        }
        content += '\n';
      }
    }
  }

  return content;
}

export async function writeStandardLibraryReferenceDocs() {
  const markdown = renderStandardLibraryReferenceMarkdown(LIBRARY_METADATA);
  const outPath = resolve('docs/STANDARD_LIBRARY_REFERENCE.md');
  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, markdown, 'utf8');
  console.log(`Wrote ${outPath}`);
}

function isDirectExecution() {
  if (!process.argv[1]) return false;
  return import.meta.url === pathToFileURL(resolve(process.argv[1])).href;
}

if (isDirectExecution()) {
  await writeStandardLibraryReferenceDocs();
}
