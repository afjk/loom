import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const inputPath = path.join(repoRoot, 'src', 'scenesync-runtime.browser.js');
const outputPath = path.join(repoRoot, 'dist', 'loomlet-scenesync-runtime.browser.js');

const source = await fs.readFile(inputPath, 'utf8');

if (/from\s+['"].*loom-dsl\.js['"]|parseDSL|compileToGraph|compileLoomSource/.test(source)) {
  throw new Error('Scene Sync browser runtime must not bundle the DSL compiler');
}

await fs.mkdir(path.dirname(outputPath), { recursive: true });
await fs.writeFile(
  outputPath,
  [
    '// Loomlet Scene Sync browser runtime bundle.',
    '// Generated by scripts/build-scenesync-runtime-browser.mjs from src/scenesync-runtime.browser.js.',
    '// This artifact evaluates graph JSON and has no network or DSL compiler dependency.',
    source
  ].join('\n'),
  'utf8'
);

const built = await fs.readFile(outputPath, 'utf8');
if (/from\s+['"]|import\s+/.test(built)) {
  throw new Error('Scene Sync browser runtime bundle must be self-contained ESM with no imports');
}

console.log(`Wrote ${path.relative(repoRoot, outputPath)} (${built.length} bytes)`);
